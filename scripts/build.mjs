// Builds app.js (src/main.ts: sign-in, then src/app.ts, bundled into one classic script that index.html loads)
// and d2link.js (src/d2, the open-source D2 Link tab, loaded when that tab is first opened).
// Both are generated — edit the source in src/, not the .js files.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

const bundled = await build({
  entryPoints: [join(root, "src/main.ts")],
  bundle: true,
  format: "iife",
  target: "es2020",
  write: false,
  legalComments: "none",
  minify: true, // the bundled sign-in library is large; minified it downloads much faster
});
const js = bundled.outputFiles[0].text;
const banner = `// OpenBeat ECG — app.js v${pkg.version}. GENERATED by \`npm run build\`; edit the source in src/, not this file.\n`;
await writeFile(join(root, "app.js"), banner + js);
console.log(`Built app.js (v${pkg.version}, ${(js.length / 1024).toFixed(1)} KB)`);

// d2link.js: D2 Link (src/d2), kept in its own script because it is open source (GNU AGPL v3, built on Gadgetbridge).
const d2 = await build({
  entryPoints: [join(root, "src/d2/index.ts")],
  bundle: true,
  format: "iife",
  target: "es2020",
  write: false,
  legalComments: "none",
  minify: false, // readable, as open-source code should be
});
const d2Banner = `// D2 Link for OpenBeat ECG — d2link.js v${pkg.version}. GENERATED by \`npm run build\` from src/d2.
// SPDX-License-Identifier: AGPL-3.0-or-later. Free software under the GNU Affero General Public License v3 or later
// (see LICENSE-D2-LINK.txt). Built on Gadgetbridge's Huawei support, https://codeberg.org/Freeyourgadget/Gadgetbridge,
// © Gadgetbridge contributors. Port © 2026 ECG-Tracking. Source: https://github.com/ECG-Tracking/Polar-H10/tree/main/src/d2
`;
await writeFile(join(root, "d2link.js"), d2Banner + d2.outputFiles[0].text);
console.log(`Built d2link.js (${(d2.outputFiles[0].text.length / 1024).toFixed(1)} KB)`);
